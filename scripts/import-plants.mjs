#!/usr/bin/env node
/**
 * Build src/lib/plants.generated.ts from data/plants.v1.json.
 *
 * `npm run typecheck` runs this first. Output is deterministic and the file
 * is written only when its bytes change, so a clean catalog is a no-op.
 * Invalid rows, duplicate ids, zoneMin warmer than zoneMax, and tag
 * conflicts exit non-zero, which fails typecheck.
 *
 * `npm run build` does not regenerate. Deploy installs omit devDependencies
 * (including Prettier), and the committed generated module is what ships.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";
import { expansionDrift } from "../src/lib/plant-climate-tags.ts";
import { plantCatalogSchema, toCatalogPlant } from "../src/lib/plant-import-schema.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const jsonPath = join(root, "data", "plants.v1.json");
const outPath = join(root, "src", "lib", "plants.generated.ts");

const SCALAR_FIELDS = [
  "id",
  "name",
  "latin",
  "kind",
  "zoneMin",
  "zoneMax",
  "sun",
  "water",
  "heightFt",
  "spreadFt",
  "note",
];

function fail(message) {
  console.error(`[plants:import] ${message}`);
  process.exit(1);
}

function readCatalog() {
  let text;
  try {
    text = readFileSync(jsonPath, "utf8");
  } catch (error) {
    fail(
      `could not read data/plants.v1.json (${error instanceof Error ? error.message : String(error)})`,
    );
  }
  let json;
  try {
    json = JSON.parse(text);
  } catch (error) {
    fail(
      `data/plants.v1.json is not JSON (${error instanceof Error ? error.message : String(error)})`,
    );
  }
  const parsed = plantCatalogSchema.safeParse(json);
  if (!parsed.success) {
    console.error("[plants:import] invalid catalog");
    for (const issue of parsed.error.issues) {
      const path = issue.path.map(String).join(".");
      console.error(`  ${path || "(catalog)"}: ${issue.message}`);
    }
    process.exit(1);
  }
  return parsed.data;
}

function emitMap(map) {
  const entries = Object.entries(map);
  if (entries.length === 0) return "{}";
  const lines = entries.map(([key, value]) => `      ${key}: ${JSON.stringify(value)},`);
  return `{\n${lines.join("\n")}\n    }`;
}

function emitPlant(plant) {
  const lines = [
    `    id: ${JSON.stringify(plant.id)},`,
    `    name: ${JSON.stringify(plant.name)},`,
    `    latin: ${JSON.stringify(plant.latin)},`,
    `    kind: ${JSON.stringify(plant.kind)},`,
    `    zoneMin: ${JSON.stringify(plant.zoneMin)},`,
    `    zoneMax: ${JSON.stringify(plant.zoneMax)},`,
    `    sun: ${JSON.stringify(plant.sun)},`,
    `    water: ${JSON.stringify(plant.water)},`,
    `    heightFt: ${JSON.stringify(plant.heightFt)},`,
    `    spreadFt: ${JSON.stringify(plant.spreadFt)},`,
    `    note: ${JSON.stringify(plant.note)},`,
    `    avoid: ${emitMap(plant.avoid)},`,
    `    caution: ${emitMap(plant.caution)},`,
  ];
  return `  {\n${lines.join("\n")}\n  }`;
}

function emitModule(plants) {
  const body = plants.map((plant) => emitPlant(plant)).join(",\n");
  return `// Generated by scripts/import-plants.mjs from data/plants.v1.json.
// Do not edit by hand. Edit the JSON, then run \`npm run plants:import\`.

import type { Plant } from "./plants";

export const PLANTS: Plant[] = [
${body},
];
`;
}

const catalog = readCatalog();
const plants = [];
for (const row of catalog.plants) {
  let plant;
  try {
    plant = toCatalogPlant(row);
  } catch (error) {
    fail(`${row.id}: ${error instanceof Error ? error.message : String(error)}`);
  }
  const drift = expansionDrift(row, plant);
  if (drift) fail(`${row.id}: ${drift}`);
  for (const field of SCALAR_FIELDS) {
    if (plant[field] !== row[field]) fail(`${row.id}: ${field} changed during import`);
  }
  plants.push(plant);
}

if (plants.length !== catalog.plants.length) {
  fail(`expected ${String(catalog.plants.length)} plants, expanded ${String(plants.length)}`);
}

const source = emitModule(plants);
const formatted = await prettier.format(source, { filepath: outPath });

let previous = null;
try {
  previous = readFileSync(outPath, "utf8");
} catch {
  previous = null;
}

if (previous === formatted) {
  console.log(`[plants:import] ${String(plants.length)} plants, up to date`);
} else {
  writeFileSync(outPath, formatted);
  console.log(
    `[plants:import] wrote ${String(plants.length)} plants to src/lib/plants.generated.ts`,
  );
}
